def add_heading_styled(text, level=1):
    h = doc.add_heading(text, level=level)
    for run in h.runs:
        run.font.name = '微软雅黑'
        run._element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
        if level == 0:
            run.font.size = Pt(22)
            run.font.color.rgb = DARK_BLUE
        elif level == 1:
            run.font.size = Pt(16)
            run.font.color.rgb = DARK_BLUE
        elif level == 2:
            run.font.size = Pt(13)
            run.font.color.rgb = TEAL
        elif level == 3:
            run.font.size = Pt(11)
            run.font.color.rgb = TEAL
    return h

def add_para(text, bold=False, size=10.5, align=None, color=None, font_name=None):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = color
    fn = font_name or '宋体'
    run.font.name = fn
    run._element.rPr.rFonts.set(qn('w:eastAsia'), fn)
    if align is not None:
        p.alignment = align
    return p

def add_table_with_style(headers, rows, col_widths=None):
    """Add a formatted table"""
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    
    # Header row
    for j, h in enumerate(headers):
        cell = table.rows[0].cells[j]
        cell.text = ''
        p = cell.paragraphs[0]
        run = p.add_run(h)
        run.font.size = Pt(9)
        run.font.bold = True
        run.font.name = '微软雅黑'
        run._element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
        run.font.color.rgb = WHITE
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        # Dark blue background
        shading = parse_xml(f'<w:shd {nsdecls("w")} w:fill="0A1F3F"/>')
        cell._element.get_or_add_tcPr().append(shading)
    
    # Data rows
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = table.rows[i+1].cells[j]
            cell.text = ''
            p = cell.paragraphs[0]
            run = p.add_run(str(val) if val is not None else '')
            run.font.size = Pt(8.5)
            run.font.name = '宋体'
            run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
            # Alternate row shading
            if i % 2 == 1:
                shading = parse_xml(f'<w:shd {nsdecls("w")} w:fill="F5F2EC"/>')
                cell._element.get_or_add_tcPr().append(shading)
    
    # Set column widths
    if col_widths:
        for row in table.rows:
            for j, w in enumerate(col_widths):
                if j < len(row.cells):
                    row.cells[j].width = Cm(w)
    
    doc.add_paragraph()  # spacing
    return table

