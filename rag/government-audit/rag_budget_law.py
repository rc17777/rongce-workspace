def search_by_tag(tag: str) -> list:
    """按标签检索"""
    return [entry for entry in BUDGET_LAW_KB if tag in entry.get("tags", [])]


def search_by_keyword(keyword: str) -> list:
    """按关键词检索（模糊匹配content和title）"""
    results = []
    for entry in BUDGET_LAW_KB:
        if keyword in entry["title"] or keyword in entry["content"]:
            results.append(entry)
    return results


def get_by_id(entry_id: str) -> dict:
    """按ID获取单条"""
    for entry in BUDGET_LAW_KB:
        if entry["id"] == entry_id:
            return entry
    return {}


