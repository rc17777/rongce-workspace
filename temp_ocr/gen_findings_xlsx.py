def style_sheet(ws, headers, col_widths, title=None, subtitle=None):
    """Apply standard styling"""
    start_row = 1
    if title:
        ws.merge_cells(start_row=start_row, start_column=1, end_row=start_row, end_column=len(headers))
        ws.cell(row=start_row, column=1, value=title).font = title_font
        start_row += 1
    if subtitle:
        ws.merge_cells(start_row=start_row, start_column=1, end_row=start_row, end_column=len(headers))
        ws.cell(row=start_row, column=1, value=subtitle).font = subtitle_font
        start_row += 1
    
    for i, (h, w) in enumerate(zip(headers, col_widths), 1):
        c = ws.cell(row=start_row, column=i, value=h)
        c.font = hdr_font; c.fill = hdr_fill; c.alignment = center; c.border = thin_border
        ws.column_dimensions[get_column_letter(i)].width = w
    return start_row + 1  # return first data row

def write_rows(ws, start_row, rows, level_col=None):
    """Write data rows with alternating fills"""
    for ri, row in enumerate(rows):
        r = start_row + ri
        for ci, val in enumerate(row, 1):
            c = ws.cell(row=r, column=ci, value=val)
            c.font = body_font; c.alignment = wrap; c.border = thin_border
        # Color by level
        if level_col is not None:
            lv = row[level_col] if level_col < len(row) else ''
            if '🔴' in str(lv): ws.cell(row=r, column=level_col+1).fill = red_fill
            elif '🟡' in str(lv): ws.cell(row=r, column=level_col+1).fill = yellow_fill

