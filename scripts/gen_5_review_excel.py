ALIGN_WRAP = Alignment(wrap_text=True, vertical='top')
ALIGN_CENTER = Alignment(horizontal='center', vertical='center', wrap_text=True)
THIN_BORDER = Border(
    left=Side(style='thin'), right=Side(style='thin'),
    top=Side(style='thin'), bottom=Side(style='thin')
)

def style_header(ws, row, max_col):
    for c in range(1, max_col+1):
        cell = ws.cell(row, c)
        cell.font = FONT_HEADER
        cell.fill = FILL_HEADER
        cell.font = Font(name='微软雅黑', size=10, bold=True, color='FFFFFF')
        cell.alignment = ALIGN_CENTER
        cell.border = THIN_BORDER

def style_cell(cell, font=FONT_NORMAL, fill=None):
    cell.font = font
    cell.alignment = ALIGN_WRAP
    cell.border = THIN_BORDER
    if fill:
        cell.fill = fill

def write_sheet_rows(ws, headers, data, start_row=1):
    """Write headers + data rows with styling"""
    for ci, h in enumerate(headers, 1):
        ws.cell(start_row, ci, h)
    style_header(ws, start_row, len(headers))
    
    for ri, row in enumerate(data, start_row+1):
        for ci, val in enumerate(row, 1):
            cell = ws.cell(ri, ci, val)
            # Determine font based on risk level
            font = FONT_NORMAL
            fill = None
            # Check for risk level in relevant columns
            risk_val = None
            if len(headers) >= 8:  # Sheet1 has 9 cols, risk=col8
                risk_val = row[7] if len(row) > 7 else None
            elif len(headers) == 7:  # Sheet2 has 7 cols, risk=col6
                risk_val = row[5] if len(row) > 5 else None
            elif len(headers) == 5 and '风险' in str(headers[-1]):  # Sheet3, risk=col5
                risk_val = row[4] if len(row) > 4 else None
            elif len(headers) == 11:  # Sheet6, risk=col11
                risk_val = row[10] if len(row) > 10 else None
            elif len(headers) == 8:  # Sheet7, risk=col7
                risk_val = row[6] if len(row) > 6 else None
            
            risk_str = str(risk_val) if risk_val else ''
            if 'P0' in risk_str:
                font = FONT_P0
                fill = FILL_P0
            elif 'P1' in risk_str:
                font = FONT_P1
                fill = FILL_P1
            elif 'P2' in risk_str:
                font = FONT_P2
                fill = FILL_P2
            elif '通过' in risk_str or '正确' in risk_str:
                fill = FILL_THRU
                
            style_cell(cell, font, fill)

