def apply_style(ws, row_num, max_col, font_style=normal_font, fill=None):
    for col in range(1, max_col+1):
        cell = ws.cell(row=row_num, column=col)
        cell.font = font_style
        cell.border = thin_border
        cell.alignment = center_align if col != 4 else left_align
        if fill:
            cell.fill = fill

def write_sheet(ws, title, data, sheet_type='all'):
    """写入数据到sheet"""
    # 标题行
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(columns))
    title_cell = ws.cell(row=1, column=1, value=title)
    title_cell.font = title_font
    title_cell.alignment = Alignment(horizontal='center', vertical='center')
    ws.row_dimensions[1].height = 35

    # 表头
    for col_idx, (col_name, width) in enumerate(zip(columns, col_widths), 1):
        cell = ws.cell(row=2, column=col_idx, value=col_name)
        cell.font = header_font_white
        cell.fill = header_fill
        cell.border = thin_border
        cell.alignment = center_align
        ws.column_dimensions[get_column_letter(col_idx)].width = width
    ws.row_dimensions[2].height = 25

    # 数据行
    for row_idx, row_data in enumerate(data, 3):
        is_warn = False
        for col_idx, value in enumerate(row_data, 1):
            cell = ws.cell(row=row_idx, column=col_idx, value=value)
            cell.font = normal_font
            cell.border = thin_border
            cell.alignment = center_align if col_idx not in [4, 7] else left_align
            if isinstance(value, str) and '⚠️' in value:
                is_warn = True
                cell.font = warn_font
        if is_warn:
            for col in range(1, len(columns)+1):
                ws.cell(row=row_idx, column=col).fill = warn_fill

    # 汇总行
    last_data_row = 2 + len(data)
    total_row = last_data_row + 2
    ws.merge_cells(start_row=total_row, start_column=1, end_row=total_row, end_column=2)
    ws.cell(row=total_row, column=1, value=f'合计人数: {len(data)}').font = Font(name='微软雅黑', bold=True, size=11)
    ws.cell(row=total_row, column=1).alignment = left_align

    # 冻结首行+表头
    ws.freeze_panes = 'A3'
    # 自动筛选
    ws.auto_filter.ref = f'A2:{get_column_letter(len(columns))}{last_data_row}'

