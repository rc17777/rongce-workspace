def biz_template(scene, desc, paths):
    body = [
        '---',
        f'title: "{scene}标准模板"',
        'scene: 项目模板',
        'tags: [融策, 审计模板, 标准作业包]',
        '---\n',
        f'# {scene}标准模板\n',
        f'> 适用说明：{desc}\n',
        '## 一、标准审计目标\n',
        '- 围绕本领域关键业务链条和资金链条，审查政策执行、程序履行、资金安全和绩效结果。',
        '- 揭示问题背后的制度缺陷、管理漏洞和责任链条，推动整改和治理提升。\n',
        '## 二、标准审前调查\n',
        '- 明确主管部门、实施单位、资金来源和业务流程。',
        '- 梳理关键台账、合同、批复、制度文件和业务系统字段。',
        '- 先列风险清单，再确定取数和核查路径。\n',
        '## 三、标准取证路径\n',
    ]
    for p in paths:
        body.append(f'- {p}')
    body.extend([
        '\n## 四、标准问题表述\n',
        '- 经审计发现，相关单位在制度执行、程序履行、资金管理或业务真实性方面存在薄弱环节。',
        '- 相关问题反映出主管部门监督不严、过程控制不到位、责任落实不充分。\n',
        '## 五、标准建议表述\n',
        '- 建议健全制度、压实责任、完善流程、强化协同。',
        '- 建议围绕问题清单限期整改，并建立回头看和长效治理机制。\n',
        '## 六、标准汇报提纲\n',
        '- 背景与目标',
        '- 关键发现',
        '- 主要风险',
        '- 整改建议',
        '- 需协调事项',
    ])
    return '\n'.join(body)


