RED_FILL = PatternFill(start_color='FFE0E0', end_color='FFE0E0', fill_type='solid')
GREEN_FILL = PatternFill(start_color='E0FFE0', end_color='E0FFE0', fill_type='solid')
YELLOW_FILL = PatternFill(start_color='FFFFE0', end_color='FFFFE0', fill_type='solid')
BLUE_FILL = PatternFill(start_color='E0E8FF', end_color='E0E8FF', fill_type='solid')
HEADER_FILL = PatternFill(start_color='0A1F3F', end_color='0A1F3F', fill_type='solid')
HEADER_FONT = Font(name='微软雅黑', bold=True, color='FFFFFF', size=11)
NORMAL_FONT = Font(name='微软雅黑', size=10)
BOLD_FONT = Font(name='微软雅黑', bold=True, size=10)
TITLE_FONT = Font(name='微软雅黑', bold=True, size=14, color='0A1F3F')
WRAP = Alignment(wrap_text=True, vertical='top')
THIN_BORDER = Border(
    left=Side(style='thin'), right=Side(style='thin'),
    top=Side(style='thin'), bottom=Side(style='thin')
)

def style_header(ws, row, max_col):
    for col in range(1, max_col+1):
        c = ws.cell(row=row, column=col)
        c.font = HEADER_FONT
        c.fill = HEADER_FILL
        c.alignment = WRAP
        c.border = THIN_BORDER

def style_data(ws, start_row, end_row, max_col):
    for r in range(start_row, end_row+1):
        for col in range(1, max_col+1):
            c = ws.cell(row=r, column=col)
            c.font = NORMAL_FONT
            c.alignment = WRAP
            c.border = THIN_BORDER

def auto_width(ws, max_col, min_w=10, max_w=50):
    for col in range(1, max_col+1):
        ws.column_dimensions[get_column_letter(col)].width = min_w

