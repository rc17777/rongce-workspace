def add_styled(doc, text, size=11, bold=False, color=None, align=None, space_after=6):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.line_spacing = 1.35
    run = p.add_run(text)
    run.font.size = Pt(size)
    run.font.name = '微软雅黑'
    run._element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
    run.bold = bold
    if color:
        run.font.color.rgb = color
    if align is not None:
        p.alignment = align
    return p

def add_title(doc, text):
    add_styled(doc, text, size=22, bold=True, color=NAVY, align=WD_ALIGN_PARAGRAPH.CENTER, space_after=16)

def add_subtitle(doc, text):
    add_styled(doc, text, size=11, color=GRAY, align=WD_ALIGN_PARAGRAPH.CENTER, space_after=12)

def add_slide_header(doc, num, title, duration=""):
    dur = f"（{duration}）" if duration else ""
    add_styled(doc, f"━━━ Slide {num} ━━━ {title} {dur}", size=14, bold=True, color=NAVY, space_after=8)

def add_body(doc, text, size=11, space_after=4):
    lines = text.strip().split('\n')
    for line in lines:
        line = line.strip()
        if not line:
            add_styled(doc, '', size=size, space_after=2)
            continue
        # Bold markers
        if line.startswith('**') and line.endswith('**'):
            add_styled(doc, line.strip('*'), size=size, bold=True, space_after=4)
        elif line.startswith('**'):
            idx = line.find('**', 2)
            if idx > 0:
                prefix = line[2:idx]
                suffix = line[idx+2:]
                p = doc.add_paragraph()
                p.paragraph_format.space_after = Pt(4)
                p.paragraph_format.line_spacing = 1.35
                run_b = p.add_run(prefix)
                run_b.font.size = Pt(size)
                run_b.font.name = '微软雅黑'
                run_b._element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
                run_b.bold = True
                run_n = p.add_run(suffix)
                run_n.font.size = Pt(size)
                run_n.font.name = '微软雅黑'
                run_n._element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
            else:
                add_styled(doc, line, size=size, space_after=4)
        else:
            add_styled(doc, line, size=size, space_after=4)

def add_separator(doc):
    add_styled(doc, '─' * 60, size=8, color=GRAY, space_after=10)

