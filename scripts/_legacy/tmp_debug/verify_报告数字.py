#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""数字勾稽验证"""
import sys
sys.stdout.reconfigure(encoding='utf-8')

def check(label, expected, actual, tolerance=1):
    ok = abs(expected - actual) <= tolerance
    icon = "OK" if ok else "XX"
    print(f'  {icon} {label}: expected={expected:,.2f}, actual={actual:,.2f}')
    return ok

print('========== 报告正文数字勾稽验证 ==========\n')

# 资产负债表验证
print('--- 资产负债表 ---')
check('资产=流动+非流动', 7372623.71, 4663304.88+2709318.83)
check('资产-负债=权益', 1523649.89, 7372623.71-5848973.82)

# 货币资金
cs = 2026078.51+1807887.60+20061.13+5.00+781.36
check('货币资金', 3854813.60, cs)

# 应收账款
ar = 79661.87+58672.00+950.00+91573.81+40202.22
check('应收账款', 271059.90, ar)

# 其他应收款
oar = 30000.00+500000.00+7431.38
check('其他应收款', 537431.38, oar)

# 固定资产
check('固定资产原值-折旧=净值', 829351.91, 1147080.19-317728.28)

# 长期待摊费用
check('长期待摊原值-摊销=余额', 1879966.92, 2674350.49-794383.57)

# 应交税费
tax = 18922.96+188.93+84865.86+333.82+143.06+95.38
check('应交税费', 104550.01, tax)

# 其他应付款
op = 4887000.00+198050.00+161291.38+156735.55
check('其他应付款', 5403076.93, op)

print('\n--- 利润表 ---')
# 2025年营业利润
op2025 = 10814312.14-8973135.37-6252.41-99430.49-14150.94-570.81
check('2025营业利润', 1720772.12, op2025)

# 2025利润总额
tp2025 = op2025+2566.15-0.20
check('2025利润总额', 1723338.07, tp2025)

# 2025净利润
np2025 = tp2025-156538.15
check('2025净利润', 1566799.92, np2025)

# 全期间净利润
check('审计期间净利润合计', 1523649.89, 1566799.92-43150.03)

print('\n--- 利润分配验证 ---')
total_inc_tax = 11829839.84
gp = total_inc_tax * 0.06
check('兜底利润(6%)', 709790.39, gp)

lr = 1523649.89 * 0.10
check('法定公积金(10%)', 152364.99, lr)

excess = gp - lr
check('超额利润(兜底-公积金)', 557425.40, excess)

print('\n========== 结果总结 ==========')
print('所有数字勾稽：均一致')
