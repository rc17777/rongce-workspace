def implementation_plan(name, cfg):
    return f'''---
title: "{name}-审计实施方案模板"
scene: 实战试点包
tags: [融策, 实战试点包, 审计实施方案]
---

# {name}｜审计实施方案模板

## 一、项目背景

本项目围绕{cfg['focus']}开展审计，重点揭示政策执行、业务真实性、程序合规、资金安全和绩效结果等方面存在的问题，推动整改和治理提升。

## 二、审计目标

- 查清重点事项的真实情况、业务流程和资金流向。
- 揭示制度执行、程序控制、数据真实性和绩效结果方面的问题。
- 推动被审计单位完善制度、压实责任、规范管理。

## 三、审计范围

- 审计期间：根据委托要求确定。
- 审计对象：主管部门、实施单位、资金使用单位及相关业务主体。
- 审计内容：围绕重点项目、重点资金、重点环节和重点数据开展。

## 四、审计重点

{chr(10).join('- ' + r for r in cfg['risks'])}

## 五、审计方法

{chr(10).join('- ' + m for m in cfg['methods'])}

## 六、工作步骤

1. 审前调查：收集政策、制度、台账、数据和业务资料。
2. 风险画像：按业务链条梳理风险点，形成疑点清单。
3. 数据分析：对关键字段、金额、时间、对象进行比对筛查。
4. 现场核查：对重点疑点开展访谈、踏勘、资料复核。
5. 定性取证：形成取证单、问题清单和证据链。
6. 成果输出：形成汇报材料、审计报告或专报。
'''


def data_list(name, cfg):
    rows = '\n'.join(f'| {i} | {d} | 主管部门/实施单位 | 原始电子表或盖章纸质件 | 用于核实业务真实性、资金流向或程序合规 | |' for i, d in enumerate(cfg['data'], 1))
    return f'''---
title: "{name}-取数清单模板"
scene: 实战试点包
tags: [融策, 实战试点包, 取数清单]
---

# {name}｜取数清单模板

| 序号 | 资料/数据名称 | 提供单位 | 格式要求 | 用途 | 备注 |
|---:|---|---|---|---|---|
{rows}

## 取数要求

- 电子数据需保留原始字段，不得仅提供汇总表。
- 涉及系统导出的，应注明系统名称、导出时间和经办人。
- 涉及资金数据的，应能追溯到支付凭证或财政指标文件。
'''


def special_report(name, cfg):
    return f'''---
title: "{name}-专报初稿模板"
scene: 实战试点包
tags: [融策, 实战试点包, 专报模板]
---

# {cfg['report_title']}

## 一、基本情况

根据工作安排，审计组围绕{cfg['focus']}开展审计，重点关注政策执行、业务真实性、资金安全和绩效结果等情况。

## 二、审计发现的主要问题

### （一）问题一：……

经审计发现，……反映出相关单位在制度执行、过程管控和责任落实方面存在薄弱环节。

### （二）问题二：……

经比对相关数据和资料，发现……疑似存在业务真实性不足、资金管理不规范或政策执行不到位等问题。

## 三、原因分析

- 制度执行不到位。
- 部门协同不充分。
- 数据治理和过程监管不足。
- 整改闭环机制不完善。

## 四、审计建议

- 建议相关单位对照问题清单限期整改。
- 建议主管部门完善制度流程，加强业务审核和数据监管。
- 建议建立长效机制，推动问题整改从个案处理向系统治理延伸。
'''


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for pack, cfg in PACKS.items():
        d = OUT / pack
        d.mkdir(parents=True, exist_ok=True)
        (d / '01-审计实施方案模板.md').write_text(implementation_plan(pack, cfg), encoding='utf-8')
        (d / '02-取数清单模板.md').write_text(data_list(pack, cfg), encoding='utf-8')
        for fname, content in COMMON_FORMS.items():
            (d / fname).write_text(content, encoding='utf-8')
        (d / '06-专报初稿模板.md').write_text(special_report(pack, cfg), encoding='utf-8')
    print(f'PRACTICAL\t{OUT}')

if __name__ == '__main__':
    main()
