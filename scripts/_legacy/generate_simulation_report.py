add_heading_styled(doc, '1. 问题描述', level=3)

add_body_text(doc, '经逐项审核发现，案例中部分三级指标的归属分类存在明显错误，主要表现在以下两个方面：')

add_body_text(doc, '第一，"路面使用性能指数"（指标序号7）被归类为"产出指标-数量指标"，而该指标实质上是衡量道路养护质量的指标，应归属于"产出指标-质量指标"。路面使用性能指数（PQI）是交通运输行业衡量路面技术状况的综合性质量指标，反映的是路面的平整度、破损程度、车辙深度等技术状况，其本质是质量维度而非数量维度。将其归入数量指标，混淆了"做了多少"与"做得怎么样"的基本区分。')

add_body_text(doc, '第二，"竣工在建项目"（指标序号8）被归类为"产出指标-数量指标"，但其指标名称存在逻辑矛盾。"竣工"和"在建"是两个互斥的状态——项目要么已竣工，要么正在建设，不存在"竣工在建"的中间状态。从指标值"≥2个项目"来看，编制者的本意可能是衡量当年竣工项目数量，属于数量指标范畴，但指标名称的不严谨导致了逻辑混淆。')

add_body_text(doc, '第三，"一段时间内便于居民出行"（指标序号15）归属于"效益指标-可持续影响指标"，但指标值"明显提升"缺乏时间限定，指标本身也未体现"可持续"的内涵。"便于居民出行"是一个即期感受类指标，与其说是可持续影响，不如归入社会效益指标更为恰当。')

