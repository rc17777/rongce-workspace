def add_table_styled(doc, headers, rows, col_widths=None, header_color='1C355E'):
    """添加带样式的表格"""
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    
    # 表头
    hdr_color = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{header_color}"/>')
    for i, header in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ''
        para = cell.paragraphs[0]
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = para.add_run(header)
        run.bold = True
        run.font.size = Pt(11)
        run.font.name = '黑体'
        run._element.rPr.rFonts.set(qn('w:eastAsia'), '黑体')
        run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        cell._element.get_or_add_tcPr().append(hdr_color)
    
    # 数据行
    for ri, row_data in enumerate(rows):
        for ci, cell_text in enumerate(row_data):
            cell = table.rows[ri + 1].cells[ci]
            cell.text = ''
            para = cell.paragraphs[0]
            para.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = para.add_run(str(cell_text))
            run.font.size = Pt(10.5)
            run.font.name = '仿宋'
            run._element.rPr.rFonts.set(qn('w:eastAsia'), '仿宋')
            # 交替行底色
            if ri % 2 == 1:
                alt_color = parse_xml(f'<w:shd {nsdecls("w")} w:fill="E8EDF5"/>')
                cell._element.get_or_add_tcPr().append(alt_color)
    
    # 设置列宽
    if col_widths:
        for ri, row in enumerate(table.rows):
            for ci, width in enumerate(col_widths):
                if ci < len(row.cells):
                    row.cells[ci].width = Inches(width)
    
    doc.add_paragraph()  # 表后空行
    return table

