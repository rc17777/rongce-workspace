add_body_text(doc, '建议二：将"竣工在建项目"的名称修改为"当年竣工项目数量"或"年度完工项目数量"，保持其"产出指标-数量指标"的分类不变，指标值相应调整为"≥X个"，并根据年度交通建设计划明确具体项目清单。')

add_body_text(doc, '建议三：将"一段时间内便于居民出行"重新分类至"效益指标-社会效益指标"，并在指标编制说明中明确衡量方式（如出行时间抽样调查）和时间基准（如与上年同期相比）。')

