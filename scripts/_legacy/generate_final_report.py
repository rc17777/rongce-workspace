# ============================================================
heading(doc, '（二）问题二：多个效益指标不可量化，定性表述模糊', level=2)

heading(doc, '1. 问题描述', level=3)
body(doc, '案例中效益指标维度的多项三级指标采用了"明显促进""明显提升""明显完善"等定性表述作为指标值，缺乏可量化的衡量标准。具体包括：指标11"促进农村地区经济发展"（指标值"明显促进"）、指标14"促进交通沿线地区经济可持续发展"（指标值"明显提升"）、指标15"一段时间内便于居民出行"（指标值"明显提升"）、指标16"完善区域路网结构"（指标值"明显完善"）。')
body(doc, '上述4项指标占据了全部18项履职效能指标的22.2%，影响面较大。定性表述型指标在绩效评价中存在根本性缺陷：一是无法客观衡量完成程度——何为"明显"、何为"不明显"没有统一标准，不同评价人员的判断可能存在巨大差异；二是评价结果高度依赖评价人员的主观判断，容易引发委托方和被评价方之间的争议，削弱绩效评价的公信力；三是不利于绩效信息的横向比较（与其他区县）和纵向比较（与历史年度），削弱了绩效管理的决策支持功能。')
body(doc, '根据《中央部门预算绩效目标管理办法》（财预〔2015〕88号）的要求，绩效指标应当"指向明确、细化量化、合理可行"。上述4项定性指标明显不符合"细化量化"的基本要求，属于需要重点整改的指标。')

