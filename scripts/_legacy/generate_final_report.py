# ============================================================
# 问题一
# ============================================================
heading(doc, '（一）问题一：三级指标分类存在归属错位', level=2)

heading(doc, '1. 问题描述', level=3)
body(doc, '经逐项审核发现，案例中部分三级指标的归属分类存在明显错误，主要表现在以下三个方面：')
body(doc, '第一，"路面使用性能指数"（指标序号7）被归类为"产出指标-数量指标"，而该指标实质上是衡量道路养护质量的指标，应归属于"产出指标-质量指标"。路面使用性能指数（PQI，Pavement Quality Index）是交通运输行业衡量路面技术状况的综合性质量指标，依据《公路技术状况评定标准》（JTG 5210）进行评定，反映的是路面的平整度、破损程度、车辙深度等技术状况，其本质是质量维度而非数量维度。将其归入数量指标，混淆了"做了多少"（数量）与"做得怎么样"（质量）的基本区分，也暴露出编制者对交通运输行业专业指标的理解不足。')
body(doc, '第二，"竣工在建项目"（指标序号8）被归类为"产出指标-数量指标"，但其指标名称存在逻辑矛盾。"竣工"和"在建"是两个互斥的状态——项目要么已竣工验收，要么正在建设过程中，不存在"既竣工又在建"的中间状态。从指标值"≥2个项目"来看，编制者的本意可能是衡量当年竣工项目数量，属于数量指标范畴，但指标名称的不严谨导致了逻辑混淆，也使得该指标在绩效评价时无法准确界定统计口径。')
body(doc, '第三，"一段时间内便于居民出行"（指标序号15）归属于"效益指标-可持续影响指标"，但指标值"明显提升"缺乏时间限定，指标本身也未体现"可持续"的内涵。"便于居民出行"是一个即期感受类指标，反映的是交通条件改善带来的出行便利度变化，与其说是可持续影响（强调长期性和代际公平），不如归入社会效益指标（强调对社会公众福祉的改善）更为恰当。')

heading(doc, '2. 修改建议', level=3)
body(doc, '建议一：将"路面使用性能指数"的分类由"产出指标-数量指标"修改为"产出指标-质量指标"，指标名称和指标值保持不变。同时，在指标编制说明中明确PQI的测算方法（按JTG 5210标准评定）、数据来源（年度公路技术状况评定报告）和评价周期（年度评定），增强指标的专业性和可操作性。')
body(doc, '建议二：将"竣工在建项目"的名称修改为"年度完工（竣工）项目数量"，保持其"产出指标-数量指标"的分类不变。在指标编制说明中明确"竣工"的认定标准（取得竣工验收证书或竣工验收鉴定书），并根据年度交通建设计划明确具体项目清单。')
body(doc, '建议三：将"一段时间内便于居民出行"重新分类至"效益指标-社会效益指标"，并在指标编制说明中明确衡量方式（如居民出行时间抽样调查）和时间基准（如以2025年为基准年，2026年出行时间较基准年下降比例）。')

