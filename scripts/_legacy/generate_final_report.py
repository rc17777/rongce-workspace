def add_table(doc, headers, rows, col_widths=None, hdr_color='1C355E'):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr_fill = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{hdr_color}"/>')
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ''
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(h)
        r.bold = True
        r.font.size = Pt(11)
        r.font.name = '黑体'
        r._element.rPr.rFonts.set(qn('w:eastAsia'), '黑体')
        r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        cell._element.get_or_add_tcPr().append(hdr_fill)
    for ri, row_data in enumerate(rows):
        for ci, ct in enumerate(row_data):
            cell = table.rows[ri + 1].cells[ci]
            cell.text = ''
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = p.add_run(str(ct))
            r.font.size = Pt(10.5)
            r.font.name = '仿宋'
            r._element.rPr.rFonts.set(qn('w:eastAsia'), '仿宋')
            if ri % 2 == 1:
                alt = parse_xml(f'<w:shd {nsdecls("w")} w:fill="E8EDF5"/>')
                cell._element.get_or_add_tcPr().append(alt)
    if col_widths:
        for row in table.rows:
            for ci, w in enumerate(col_widths):
                if ci < len(row.cells):
                    row.cells[ci].width = Inches(w)
    doc.add_paragraph()
    return table

