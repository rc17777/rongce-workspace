def add_indicator_sheet(name, title_text, rows):
    ws = wb.create_sheet(name)
    cols = ['一级维度','二级指标','三级评价要点','指标说明/检查重点','分值','评分标准','计分口径','证明材料清单','责任主体','检查方法','风险等级','备注']
    title(ws, title_text, len(cols)); header(ws, 3, cols)
    add_rows(ws, rows)
    tr = ws.max_row + 1; ws.cell(tr,1,'合计'); ws.cell(tr,5,f'=SUM(E4:E{tr-1})')
    for c in range(1,len(cols)+1):
        ws.cell(tr,c).fill = PatternFill('solid', fgColor=light_gold); ws.cell(tr,c).font = Font(name='微软雅黑', bold=True)
    style_sheet(ws)
    for r in range(4, tr):
        dim = ws.cell(r,1).value or ''
        fill = light_blue if '组织' in dim else light_green if '业务' in dim else light_gold
        ws.cell(r,1).fill = PatternFill('solid', fgColor=fill)
    ws.conditional_formatting.add(f'K4:K{tr-1}', CellIsRule(operator='equal', formula=['"高"'], fill=red_fill))
    ws.auto_filter.ref = f"A3:{get_column_letter(len(cols))}{tr}"
    autosize(ws, {'A':18,'B':24,'C':28,'D':46,'E':8,'F':50,'G':28,'H':42,'I':20,'J':24,'K':10,'L':24})

