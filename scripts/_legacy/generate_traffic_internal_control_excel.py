def title(ws, text, last_col):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=last_col)
    c = ws.cell(1,1,text); c.fill = header_fill
    c.font = Font(name='微软雅黑', size=15, bold=True, color=white)
    c.alignment = Alignment(horizontal='center', vertical='center')
    ws.row_dimensions[1].height = 32

def header(ws, row, cols, fill=teal):
    for i, h in enumerate(cols, 1):
        c = ws.cell(row, i, h); c.fill = PatternFill('solid', fgColor=fill)
        c.font = Font(name='微软雅黑', size=10, bold=True, color=white)
        c.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
        c.border = Border(left=thin, right=thin, top=medium, bottom=medium)

def style_sheet(ws, freeze='A4'):
    ws.freeze_panes = freeze; ws.sheet_view.showGridLines = False
    for row in ws.iter_rows():
        for cell in row:
            cell.alignment = Alignment(vertical='center', wrap_text=True)
            cell.border = border
            cell.font = Font(name='微软雅黑', size=10)
    ws.page_setup.orientation = 'landscape'; ws.page_setup.paperSize = ws.PAPERSIZE_A4
    ws.page_margins.left = 0.3; ws.page_margins.right = 0.3; ws.page_margins.top = 0.5; ws.page_margins.bottom = 0.5
    ws.sheet_properties.pageSetUpPr.fitToPage = True; ws.page_setup.fitToWidth = 1; ws.page_setup.fitToHeight = 0

def autosize(ws, widths):
    for col, width in widths.items(): ws.column_dimensions[col].width = width
    for row in range(1, ws.max_row+1): ws.row_dimensions[row].height = max(ws.row_dimensions[row].height or 18, 24)

def add_rows(ws, rows, start=4):
    for r, row in enumerate(rows, start):
        for c, v in enumerate(row, 1): ws.cell(r, c, v)

