def style_title(ws, text, fill):
    ws.merge_cells('A1:K1')
    c = ws['A1']; c.value = text; c.font = title_font; c.fill = fill
    c.alignment = Alignment(horizontal='center', vertical='center')
    ws.row_dimensions[1].height = 40
    ws.merge_cells('A2:K2')
    ws['A2'].value = '委派单位：成都市轨道资源经营管理有限公司 | 被审计公司：天府智厨 | 审计期间：2020年6月-2023年6月'
    ws['A2'].font = Font(name='Microsoft YaHei', size=9, italic=True)

def write_hdr(ws, row, headers, fill):
    for c, h in enumerate(headers, 1):
        cell = ws.cell(row=row, column=c, value=h)
        cell.font = hdr_font; cell.fill = fill; cell.alignment = center_align; cell.border = thin_border

def write_row(ws, row, data, zebra):
    for c, v in enumerate(data, 1):
        cell = ws.cell(row=row, column=c, value=v)
        cell.font = body_font; cell.alignment = wrap_align; cell.border = thin_border
        if row % 2 == 0: cell.fill = zebra

def write_sec(ws, row, text, fill):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=11)
    c = ws.cell(row=row, column=1, value=text)
    c.font = sec_font; c.fill = fill; c.alignment = Alignment(vertical='center'); c.border = thin_border
    for col in range(2, 12):
        ws.cell(row=row, column=col).fill = fill
        ws.cell(row=row, column=col).border = thin_border

