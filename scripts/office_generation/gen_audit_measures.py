alt_fill = PatternFill(start_color='F2F7FB', end_color='F2F7FB', fill_type='solid')

thin_border = Border(
    left=Side(style='thin'), right=Side(style='thin'),
    top=Side(style='thin'), bottom=Side(style='thin')
)
wrap_align = Alignment(wrap_text=True, vertical='center')
center_align = Alignment(horizontal='center', vertical='center', wrap_text=True)

def set_col_widths(ws, widths):
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w

def write_title(ws, row, text, merge_end_col):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=merge_end_col)
    cell = ws.cell(row=row, column=1, value=text)
    cell.font = title_font; cell.fill = title_fill; cell.alignment = center_align
    for c in range(1, merge_end_col+1):
        ws.cell(row=row, column=c).fill = title_fill
        ws.cell(row=row, column=c).border = thin_border
    return row + 1

def write_headers(ws, row, headers, fill=None):
    if fill is None: fill = header_fill
    for i, h in enumerate(headers, 1):
        cell = ws.cell(row=row, column=i, value=h)
        cell.font = header_font; cell.fill = fill
        cell.alignment = center_align; cell.border = thin_border
    return row + 1

def write_row(ws, row, data, is_alt=False, col_fills=None):
    for i, val in enumerate(data, 1):
        cell = ws.cell(row=row, column=i, value=val)
        cell.font = body_font; cell.alignment = wrap_align; cell.border = thin_border
        if is_alt and col_fills is None:
            cell.fill = alt_fill
        elif col_fills and i in col_fills:
            cell.fill = col_fills[i]
    return row + 1

def write_category_row(ws, row, text, col_count):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=col_count)
    cell = ws.cell(row=row, column=1, value=text)
    cell.font = Font(name='微软雅黑', size=11, bold=True, color='1F4E79')
    cell.fill = sub_header_fill; cell.alignment = Alignment(vertical='center')
    for c in range(1, col_count+1):
        ws.cell(row=row, column=c).fill = sub_header_fill
        ws.cell(row=row, column=c).border = thin_border
    return row + 1

def write_sub_info(ws, row, text, col_count):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=col_count)
    cell = ws.cell(row=row, column=1, value=text)
    cell.font = Font(name='微软雅黑', size=10, color='1F4E79')
    cell.fill = sub_header_fill; cell.alignment = center_align
    for c in range(1, col_count+1):
        ws.cell(row=row, column=c).fill = sub_header_fill
        ws.cell(row=row, column=c).border = thin_border
    return row + 1

