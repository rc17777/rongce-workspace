add_article(doc, '十六', '客户表扬/批评处理：\n1. 客户书面表扬（邮件、信件）：由部门负责人确认后，抄送人力资源部，纳入员工绩效考核正向加分\n2. 客户口头表扬：重大项目客户的口头表扬由项目经理记录并汇报\n3. 客户批评/不满：参见第五章投诉处理流程')

add_chapter(doc, '五', '客户投诉处理')

add_article(doc, '十七', '投诉受理：\n1. 任何员工接到客户投诉（含口头投诉），必须在1个工作日内记录并报告部门负责人\n2. 投诉渠道：客户可通过电话、邮件、微信、面谈等方式向对接人或公司任何人员反映\n3. 投诉登记：接到投诉后填写《客户投诉登记表》（见附件3），编号存档\n4. 不得以"不归我管""我不清楚"等理由拒绝受理或推诿')

add_article(doc, '十八', '投诉分级：\n1. 一般投诉（L1）：服务态度、非关键成果的小错误、沟通不及时等\n2. 重要投诉（L2）：成果质量问题、交付延迟、费用争议、服务内容与合同不符\n3. 严重投诉（L3）：可能引起法律纠纷、政府主管部门介入、媒体关注等')

add_article(doc, '十九', '投诉处理时限：\n1. L1投诉：部门负责人在1个工作日内联系客户回应，3个工作日内解决\n2. L2投诉：业务线总监在1个工作日内联系客户回应，5个工作日内提出解决方案，经总经理审批后回复客户\n3. L3投诉：总经理在接到报告的24小时内亲自或指定负责人联系客户，启动应急处理流程')

add_article(doc, '二十', '投诉处理原则：\n1. 先处理情绪、再处理问题：第一时间表达歉意和重视，不急着辩解\n2. 调查清楚再回复：不凭猜测答复客户，应核实事实后再做回应\n3. 闭环管理：投诉从登记、调查、处理、回复到改进，全过程有记录\n4. 内部追因：每起投诉处理完毕后应做内部复盘，分析根源并改进\n5. 不打击报复：公司禁止因客户投诉对相关员工进行不当处理（以事实为依据的正常追责除外）')

