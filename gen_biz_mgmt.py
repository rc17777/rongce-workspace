add_article(doc, '四', '客户分级标准：按年度合作金额和客户战略价值两个维度，将客户分为A、B、C三个等级。')

add_article(doc, '五', 'A级客户（战略客户）：满足以下任一条件：\n1. 上年度合作金额超过50万元\n2. 连续合作3年及以上且每年都有业务往来\n3. 为政府部门（含财政局、审计局、发改委及各委办局等）和大型国有企业\n4. 虽合作金额未达标准但具有重要行业影响力或引荐价值\nA级客户维护要求：\n- 部门负责人以上每季度至少走访1次\n- 重要节日（春节、中秋）由公司层面送礼问候\n- 公司重大活动、资质升级等信息主动通知\n- 客户需求48小时内响应')

add_article(doc, '六', 'B级客户（重点客户）：满足以下任一条件：\n1. 上年度合作金额在10万-50万元之间\n2. 连续合作2年及以上\n3. 有较大增长潜力的客户\nB级客户维护要求：\n- 项目经理以上每半年至少走访1次\n- 重要节日由部门层面送礼问候\n- 客户需求3个工作日内响应')

