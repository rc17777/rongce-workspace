add_article(doc, '十', '客户联系档案管理：\n1. 客户负责人应建立和维护《客户联系档案》（见附件1），记录以下信息：\n   a. 客户基本信息（单位名称、地址、联系人、联系方式、职务）\n   b. 客户历史合作记录（项目名称、时间、金额、类型）\n   c. 客户走访记录（走访时间、走访人、交流内容、客户意见）\n   d. 客户重大事项（人事变动、机构调整、新政策影响等）\n2. 《客户联系档案》由各部门自存电子版，每季度更新一次\n3. 涉及政府部门的客户信息，注意区分可共享信息和保密信息')

add_article(doc, '十一', '客户走访要求：\n1. 走访前应做充分准备：了解客户近期动态、本项目履约情况、准备交流话题\n2. 走访应围绕：了解客户最新需求、反馈我方工作进展、听取意见建议\n3. 走访后3个工作日内形成《客户走访记录》，录入客户联系档案\n4. 走访中收集的客户需求，应在回公司后1周内给予反馈\n5. 跨部门的大型客户，由业务线总监协调联合走访')

