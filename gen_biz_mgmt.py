def chinese_num(n):
    """Convert 1-20 to Chinese numerals"""
    nums = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九', '十',
            '十一', '十二', '十三', '十四', '十五', '十六', '十七', '十八', '十九', '二十']
    return nums[n] if n < len(nums) else str(n)

