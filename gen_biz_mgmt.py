add_article(doc, '三', '客户关系管理基本原则：\n1. 分类管理：根据客户价值和合作潜力分级，差异化配置维护资源\n2. 责任到人：每个客户指定明确的客户负责人，避免多头联系或无人负责\n3. 主动维护：不等客户来找问题，主动走访、回访、了解需求\n4. 长期思维：不以短期项目利润衡量客户价值，注重长期合作关系培育\n5. 立体关系：建立多层次、多岗位的客户关系网络，避免关系过于单一')

