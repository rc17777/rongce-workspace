def _bg(c,hx):
    tc=c._tc.get_or_add_tcPr(); s=OxmlElement('w:shd'); s.set(qn('w:val'),'clear'); s.set(qn('w:color'),'auto'); s.set(qn('w:fill'),hx); tc.append(s)
def _cf(c,n,sz,b=False,cl=None):
    for p in c.paragraphs:
        p.paragraph_format.space_before=Pt(2); p.paragraph_format.space_after=Pt(2)
        for r in p.runs: r.font.name=n; r.font.size=Pt(sz); r.font.bold=b
        if cl:
            for r in p.runs: r.font.color.rgb=RGBColor.from_string(cl)
def _xh(ws):
    for c in ws[1]: c.fill=NV; c.font=HF; c.alignment=Alignment(horizontal='center',vertical='center',wrap_text=True); c.border=BO
def _xb(ws,sr,er):
    for r in range(sr,er+1):
        for c in ws[r]: c.font=WF; c.border=BO; c.alignment=Alignment(vertical='center',wrap_text=True)

def tbl(doc,hdr,rows,cw=None):
    t=doc.add_table(rows=1+len(rows),cols=len(hdr)); t.style='Table Grid'; t.alignment=WD_TABLE_ALIGNMENT.CENTER
    for ci,h in enumerate(hdr):
        cl=t.rows[0].cells[ci]; cl.text=h; _bg(cl,'0A1F3F'); _cf(cl,'微软雅黑',10.5,True,'C5955C')
    for ri,row in enumerate(rows):
        for ci,v in enumerate(row):
            cl=t.rows[ri+1].cells[ci]; cl.text=str(v) if v else ''; _cf(cl,'微软雅黑',10)
            if ri%2==0: _bg(cl,'F5F2EC')
    if cw:
        for ci,w in enumerate(cw):
            for row in t.rows: row.cells[ci].width=Cm(w)
    return t

def _H(doc,t,lvl):
    sz={1:(20,True,True),2:(15,True,False),3:(13,True,False),4:(12,True,False)}.get(lvl,(12,True,False))
    p=doc.add_paragraph(); r=p.add_run(t); r.font.name='微软雅黑'; r.font.size=Pt(sz[0]); r.font.bold=sz[1]
    r.font.color.rgb=RGBColor.from_string('1A5C6E' if lvl>=3 else '0A1F3F')
    if sz[2]: p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before=Pt(12); p.paragraph_format.space_after=Pt(4)

def _B(doc,t):
    p=doc.add_paragraph(style='List Bullet'); r=p.add_run(t); r.font.name='宋体'; r.font.size=Pt(12)

def _P(doc,t):
    p=doc.add_paragraph(); r=p.add_run(t); r.font.name='宋体'; r.font.size=Pt(12)

def _Q(doc,title,items):
    if title: _H(doc,title,3)
    for ti,tx in items:
        _H(doc,ti,4); _P(doc,tx)

