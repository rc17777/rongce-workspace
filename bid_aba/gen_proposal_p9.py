P(doc, '概算执行偏差分析的常用方法有两种：一是逐项对比法，即将每个单项工程的实际投资与概算投资进行逐一比对，分析偏差较大的项目，查找偏差原因。二是整体分析指标法，即计算项目整体的投资偏差率、工程量偏差率、单价偏差率等指标，从总体上把握概算执行情况。对于偏差超过一定幅度（如15%）的，应当深入分析原因，判断是否合理。概算执行的偏差可能是由多种原因造成的，包括工程量调整、材料价格波动、设计变更、政策调整等。审核人员应当对偏差原因进行客观分析，区分合理偏差与不合理偏差，作为审核结论的重要依据。')

