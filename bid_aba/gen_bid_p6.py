P(doc, '审核证据的质量评价标准包括：相关性，即证据与审核发现的事项是否直接相关，能否支持审核结论；可靠性，即证据来源是否可靠、内容是否真实，外部证据通常比内部证据更可靠；充分性，即证据的数量是否足够支持审核结论，对于重大事项应当获取充分证据，对于一般事项可以适当减少证据数量。')

