def style_range(ws, row_start, row_end, col_start, col_end, font=None, fill=None, alignment=None):
    for r in range(row_start, row_end+1):
        for c in range(col_start, col_end+1):
            cell = ws.cell(row=r, column=c)
            cell.border = thin_border
            if font: cell.font = font
            if fill: cell.fill = fill
            if alignment: cell.alignment = alignment

def add_title_row(ws, row, title, col_count):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=col_count)
    cell = ws.cell(row=row, column=1, value=title)
    cell.font = title_font
    cell.fill = title_fill
    cell.alignment = Alignment(horizontal='center', vertical='center')
    cell.border = thin_border
    ws.row_dimensions[row].height = 36

def add_header_row(ws, row, headers, col_start=1):
    for i, h in enumerate(headers):
        cell = ws.cell(row=row, column=col_start+i, value=h)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = center
        cell.border = thin_border
    ws.row_dimensions[row].height = 24

