def shdr(ws, r, n, txt=None):
    if txt:
        ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=n)
        c = ws.cell(row=r, column=1)
        c.value = txt
        c.font = Font(name='微软雅黑', bold=True, size=10, color='FFFFFF')
        c.fill = PatternFill(start_color='1A5C6E', end_color='1A5C6E', fill_type='solid')
        c.alignment = Alignment(vertical='center')
    for i in range(1, n+1):
        ws.cell(row=r, column=i).border = thin_border
        if i > 1 and txt:
            ws.cell(row=r, column=i).fill = PatternFill(start_color='1A5C6E', end_color='1A5C6E', fill_type='solid')

def data(ws, r, n, vals, status):
    """status: green/yellow/red/gray"""
    fill_map = {'green': green_fill, 'yellow': yellow_fill, 'red': red_fill, 'gray': gray_fill}
    fill = fill_map.get(status)
    for i, v in enumerate(vals, 1):
        c = ws.cell(row=r, column=i)
        c.value = v
        c.font = data_font
        c.alignment = wrap
        c.border = thin_border
        if fill:
            c.fill = fill
    # 状态列单独加粗
    status_cell = ws.cell(row=r, column=8)
    if status == 'red':
        status_cell.font = red_font

