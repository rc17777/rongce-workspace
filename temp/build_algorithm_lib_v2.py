def fill_algorithm_card(ws, algo, start_row):
    r = start_row
    # Title row
    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=3)
    title_cell = ws.cell(row=r, column=1, value=f'算法卡：{algo["sn"]} — {algo["name"]}')
    title_cell.font = Font(name='微软雅黑', size=14, bold=True, color='FFFFFF')
    title_cell.fill = PatternFill(start_color='0A1F3F', end_color='0A1F3F', fill_type='solid')
    title_cell.alignment = Alignment(horizontal='center', vertical='center')
    for c in range(1, 4):
        ws.cell(row=r, column=c).border = thin_border
        ws.cell(row=r, column=c).fill = PatternFill(start_color='0A1F3F', end_color='0A1F3F', fill_type='solid')
    r += 1

    # Headers
    for c, h in enumerate(['要素名称', '重要级别', '填写内容'], 1):
        cell = ws.cell(row=r, column=c, value=h)
        cell.font = header_font
        cell.fill = header_fill
        cell.border = thin_border
        cell.alignment = center_align
    r += 1

    # Fill each field
    for name, level, key, row_h in field_map:
        val = algo.get(key, '——') if key else ('v2.0 / 融策算法工作组 / 融策平头哥')
        if val is None:
            val = '——'
        # 要素名称 (col 1)
        cell_name = style_data_cell(ws, r, 1)
        cell_name.value = name
        if level == '必须':
            cell_name.font = Font(name='微软雅黑', size=10, bold=True, color='CC0000')
        # 重要级别 (col 2)
        cell_level = style_data_cell(ws, r, 2)
        cell_level.value = level
        cell_level.alignment = center_align
        if level == '必须':
            cell_level.font = Font(name='微软雅黑', size=10, bold=True, color='CC0000')
        # 内容 (col 3) - 先写值再合并
        cell_val = style_data_cell(ws, r, 3)
        cell_val.value = str(val)
        if row_h > 1:
            end_row = r + row_h - 1
            # 合并col1和col2同理
            ws.merge_cells(start_row=r, start_column=1, end_row=end_row, end_column=1)
            ws.merge_cells(start_row=r, start_column=2, end_row=end_row, end_column=2)
            ws.merge_cells(start_row=r, start_column=3, end_row=end_row, end_column=3)
            # borders for merged area
            for mr in range(r, end_row + 1):
                for mc in range(1, 4):
                    ws.cell(row=mr, column=mc).border = thin_border
                    ws.cell(row=mr, column=mc).alignment = wrap_align
            r = end_row + 1
        else:
            r += 1
    return r

