def get_constraints_for_agent(agent_name=None, biz_type=None, include_lessons=True):
    """
    根据 Agent 和业务线获取约束集。

    参数:
      agent_name: Agent ID（contract_hound/bid_hunter/...）
      biz_type: 审计类型简称（经济责任/绩效/招投标/预算执行/国企/专项资金/收支/工程/补贴）
      include_lessons: 是否包含 L3 历史教训

    返回: 约束文本字符串，可直接插入 spawn task 的 system prompt 前面
    """
    parts = []

    # L0: 通用约束
    parts.append(UNIVERSAL_CONSTRAINTS.strip())

    # L1: 业务线约束
    if biz_type:
        # 尝试精确匹配
        if biz_type in BIZ_CONSTRAINTS:
            parts.append(BIZ_CONSTRAINTS[biz_type].strip())
        else:
            # 模糊匹配
            for key, text in BIZ_CONSTRAINTS.items():
                if key in biz_type or biz_type in key:
                    parts.append(text.strip())
                    break

    # L2: Agent角色约束
    if agent_name and agent_name in AGENT_CONSTRAINTS:
        parts.append(AGENT_CONSTRAINTS[agent_name].strip())

    # L3: 历史教训
    if include_lessons:
        parts.append(LESSONS_LEARNED.strip())

    return '\n\n'.join(parts)


